-- PostgreSQL schema (ledger schema)。从 SQLite SCHEMA 平移 + 把历史上所有
-- PRAGMA/ALTER TABLE 补列迁移合并成最终形态。时间戳/日期列一律 TEXT, 默认值用
-- utc_now_text() 产出与 SQLite 时代逐字节一致的 UTC 文本 'YYYY-MM-DD HH:MM:SS'
-- (resolve_action_time 等逻辑依赖这个格式, 不能改成 timestamptz)。
-- 布尔语义列用 SMALLINT 0/1 (SQL 里到处是 enabled = 1 这类比较, 换 boolean 要改全库)。
-- 必须先建 schema: 连接的 search_path = 'ledger,public', ledger 不存在时建表会静默落进
-- public, 之后 market/ledger 的边界就乱了。
CREATE SCHEMA IF NOT EXISTS ledger;

CREATE OR REPLACE FUNCTION utc_now_text() RETURNS text AS $$
SELECT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH:MM:SS')
$$ LANGUAGE sql;


-- 重新生成: 改 database.py 的 SCHEMA 后重跑导出脚本, 整文件覆盖(不含历史)。
-- PostgreSQL schema (ledger schema)。从 SQLite SCHEMA 平移 + 把历史上所有
-- PRAGMA/ALTER TABLE 补列迁移合并成最终形态。日期/时间戳列(purchase_date/created_at/
-- updated_at/quote_time/fetched_at)用真类型 DATE/TIMESTAMP(北京时间墙钟), 默认值
-- utc_now_ts(); resolve_action_time 等逻辑依赖的 'YYYY-MM-DD HH:MM:SS' 文本形态由
-- db.py 的类型 codec 在读写边界还原。纯日期列不用 timestamptz(避免会话时区歧义)。
-- 其余历史时间列(executed_at/sold_back_at/first_seen...)保持 TEXT, 默认 utc_now_text()。
-- 布尔语义列用 SMALLINT 0/1 (SQL 里到处是 enabled = 1 这类
-- 比较, 换 boolean 要改全库)。direction 用 SMALLINT 1=多/0=空, 读写边界在
-- database.py 的 CRUD 层翻译成 'LONG'/'SHORT'。
-- 必须先建 schema: 连接的 search_path = 'ledger,public', ledger 不存在时建表会静默落进
-- public, 之后 market/ledger 的边界就乱了。
CREATE SCHEMA IF NOT EXISTS ledger;

-- 两个时间函数: utc_now_ts() 产出 timestamp(北京时间墙钟, 不带时区) —— 日期/时间戳列
-- (purchase_date/created_at/updated_at/quote_time/fetched_at, 类型 DATE/TIMESTAMP)的默认值;
-- utc_now_text() 产出同格式的 text —— 仍是 TEXT 的历史时间列(如 executed_at/first_seen)用。
-- date_trunc 去微秒: 文本形态与老数据 'YYYY-MM-DD HH:MM:SS' 逐字节一致。
CREATE OR REPLACE FUNCTION utc_now_ts() RETURNS timestamp AS $$
SELECT date_trunc('second', now() AT TIME ZONE 'Asia/Shanghai')
$$ LANGUAGE sql;

CREATE OR REPLACE FUNCTION utc_now_text() RETURNS text AS $$
SELECT to_char(now() AT TIME ZONE 'Asia/Shanghai', 'YYYY-MM-DD HH:MM:SS')
$$ LANGUAGE sql;


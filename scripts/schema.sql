-- 每日组合市值快照(收盘后记一次): 机器人/加密等无价史资产的真实市值序列,
-- 净值曲线用它替代成本基线(快照攒得越久, 这部分曲线越真)。
-- day_pnl/base_value 给盈亏日历: 当日盈亏(券商现金流口径, services/today_pnl)和
-- 比例分母(≈昨收市值口径总值)。价格是易逝数据, 事后回算要逐标的补历史价,
-- 所以当天的盈亏只在当天钉下来。
CREATE TABLE IF NOT EXISTS portfolio_snapshots (
    user_id BIGINT NOT NULL DEFAULT 0,
    snap_date TEXT NOT NULL,             -- YYYY-MM-DD
    total_value DOUBLE PRECISION NOT NULL,
    by_asset TEXT,                       -- JSON {"EXT:<id>"|"A:<code>": value}
    day_pnl DOUBLE PRECISION,            -- 当日盈亏(¥, 含手续费); NULL=老快照没记
    base_value DOUBLE PRECISION,         -- 当日盈亏的分母(≈昨收市值口径总值)
    created_at TIMESTAMP DEFAULT utc_now_ts(),
    PRIMARY KEY (user_id, snap_date)
);

-- 自选观察池(在跟踪但未必持有的票)。分组不在这张表上, 见 watchlist_group。
CREATE TABLE IF NOT EXISTS watchlist (
    user_id BIGINT NOT NULL DEFAULT 0,
    stock_code TEXT NOT NULL,
    stock_name TEXT,
    added_at TEXT,                       -- YYYY-MM-DD
    added_price DOUBLE PRECISION,        -- 加自选时现价(看"自选以来"涨跌)
    created_at TIMESTAMP DEFAULT utc_now_ts(),
    sort_order DOUBLE PRECISION DEFAULT 0,  -- 全局手动位次(「全部」视图用; 与分组无关)
    PRIMARY KEY (user_id, stock_code)
);

-- 观察池的分组成员表: 一行 = 这只票在这个分组里。一票多组。
-- 为什么不是 watchlist 上的一列: 单值列只能表达"属于一个组", 而同一只票常常既属于
-- 「高端内存」又属于「博弈」。组内手动位次同理 —— 每个组各有一份顺序, 挂在 watchlist
-- 上的话一只票只能有一个位次, 进第二个组就必然跟第一个组抢。
-- 默认组「自选」在这张表里没有行: 一只票在本表里查不到任何分组 = 还没归组。
CREATE TABLE IF NOT EXISTS watchlist_group (
    user_id BIGINT NOT NULL DEFAULT 0,
    stock_code TEXT NOT NULL,
    grp TEXT NOT NULL,                   -- 分组名(非空; 空串是"未归组", 不占行)
    group_order DOUBLE PRECISION DEFAULT 0,   -- 该组内的手动位次(各组独立)
    created_at TIMESTAMP DEFAULT utc_now_ts(),
    PRIMARY KEY (user_id, stock_code, grp)
);

-- 全市场代码↔名称字典(个股 + 场内基金 + 期货品种): 搜股的匹配底表。
-- 现拉一次要 20s+(stock_info_a_code_name 17 个分页 + ETF 表), 每次重启都重付, 首次
-- 搜索被阻塞几十秒。落盘后重启即时可用, 过期只在后台刷。
-- 分类与费率不在本表: sub_assets_type 关联 assets_classify(人工维护的分类目录),
-- 币种/保证金率/开平仓费率都从那边按小类取。
CREATE TABLE IF NOT EXISTS symbol_dict (
    code TEXT PRIMARY KEY,               -- 股票: 600111.SH / 00700.HK; 期货/期权品种: CU / IO(品种级, 合约按品种+月份拼)
    name TEXT NOT NULL,
    ticker TEXT,                         -- 裸码: 600111 / 00700 / CU(搜股匹配键)
    sub_assets_type TEXT NOT NULL,       -- 资产小类 → assets_classify.sub_assets_type(a_comm_stock/cn_futures/...)
    exchange TEXT,                       -- 交易所: SH/SZ/BJ/HKEX/SHF/DCE/CZCE/CFE/INE/GFEX...
    industry_sw TEXT,                    -- 申万行业
    industry_gics TEXT,                  -- GICS 行业
    trade_amount INTEGER,                -- 每手数量/合约乘数(期货品种行): 沪铜 5 / 期权 10000
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_symbol_dict_sub_assets_type ON symbol_dict(sub_assets_type);
CREATE INDEX IF NOT EXISTS idx_symbol_dict_exchange ON symbol_dict(exchange);

-- 资产分类目录(**人工维护**): 三级分类(大类/中类/小类) + 每小类的计价币种、交易属性与费率。
-- symbol_dict.sub_assets_type → 本表 sub_assets_type(PK)。新增一类资产改这张表, 不改代码。
-- 费率是比例口径(× 名义金额, 0.0001 = 万一); margin_rate 小数(0.10 = 10%)。
CREATE TABLE IF NOT EXISTS assets_classify (
    assets_class TEXT NOT NULL,          -- 大类: stock/fund/fix-income/commodity/crypto/derivatives/cash_equal/forex/insurance
    assets_class_name TEXT NOT NULL,
    main_assets_type TEXT NOT NULL,      -- 中类: common_share/etf_fund/futures/crypto_perpetual...
    assets_type_name TEXT NOT NULL,
    sub_assets_type TEXT NOT NULL,       -- 小类(关联键): a_comm_stock/cn_etf_fund/cn_futures/crypto_spot...
    sub_assets_type_name TEXT NOT NULL,
    currency TEXT,                       -- 计价货币: CNY/HKD/USD/'U'(USDT)
    trade BOOLEAN,                       -- 是否可交易
    asset_owner TEXT,
    risk_level TEXT,
    data_source TEXT,                    -- 行情/数据源: ths/...
    margin_rate DOUBLE PRECISION,        -- 保证金率(期货/期权/合约类)
    open_fee_rate DOUBLE PRECISION,      -- 开仓费率(比例)
    close_fee_rate DOUBLE PRECISION,     -- 平昨费率(比例)
    close_today_fee_rate DOUBLE PRECISION, -- 平今费率(比例)
    PRIMARY KEY (sub_assets_type)
);
CREATE INDEX IF NOT EXISTS idx_assets_classify_assets_class ON assets_classify(assets_class);
CREATE INDEX IF NOT EXISTS idx_assets_classify_main_assets_type ON assets_classify(main_assets_type);
CREATE INDEX IF NOT EXISTS idx_assets_classify_risk_level ON assets_classify(risk_level);


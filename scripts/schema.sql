    name TEXT NOT NULL DEFAULT '',
    sub_assets_type TEXT,                -- 关联 assets_classify.sub_assets_type(该表主键, sub→大类/中类/费率
                                         --   均可查: 大类统一命名从目录派生); 建仓表单所选小类

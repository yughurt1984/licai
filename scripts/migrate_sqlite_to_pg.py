"""一次性迁移: SQLite portfolio.db → PostgreSQL (ledger schema)。

用法:
    python scripts/migrate_sqlite_to_pg.py            # 迁移(跳过已迁移的表, 增量补齐)
    python scripts/migrate_sqlite_to_pg.py --truncate # 先清空 ledger 各表再迁(可重复跑)
    python scripts/migrate_sqlite_to_pg.py --check    # 只比对行数, 不写库

做法:
- 以 SQLite 侧的实际列为准逐表搬运; PG 侧 schema 是最终形态, 老库缺的列补 NULL。
- 显式写入 id (GENERATED BY DEFAULT AS IDENTITY 允许), 完了把每个表的 identity 序列
  复位到 MAX(id), 否则新插入会撞主键。
- 校验: 每张表 SQLite 行数 vs PG 行数, 全部一致才打 PASS。

注意: symbol_dict 已瘦身为"代码字典 + sub_assets_type 关联 assets_classify"(子类 NOT NULL)。
SQLite 老表没有 sub_assets_type, 这张表会迁移失败 —— 跑完迁移后用 import_symbol_dict.py
重新灌入(分类键脚本里按来源映射)。费率/保证金率在 assets_classify 人工维护, 不随迁移走。
"""
from __future__ import annotations

import argparse
import asyncio
import os
import sqlite3
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import asyncpg

from config import config

# 迁移顺序 = 导出顺序(无外键, 只是业务可读性)。kline_cache 在列 —— 数据一并搬,
# 它是应用内的日K缓存, 搬过去第一天概念回溯/涨停回测就有数据可用。
# brokers 放最前: holdings 的 broker 券商名要按它回填 broker_id。
TABLES = [
    "brokers",
    "holdings", "trade_log", "alert_config", "custom_alerts", "app_config",
    "unwind_plans", "unwind_tranches", "external_assets", "external_asset_actions",
    "position_actions", "morning_briefings", "portfolio_snapshots",
    "watchlist", "watchlist_group", "symbol_dict", "kline_cache",
    "sector_share_history", "market_volume_history", "sentiment_history",
    "limit_up_pool", "stock_tag", "cashflow_monthly", "dca_schedules",
    "position_thesis", "thesis_revision", "ask_session", "ask_message", "ask_run",
    "tool_gap", "prompt_rule", "user_memory", "trade_plan",
]

# holdings 列/类型映射(PG 侧已按新规格调整): stock_code→code, stock_name→name,
# broker(券商名)→broker_id, direction 'LONG'/'SHORT'→1/0, 数值列→NUMERIC(Decimal 化),
# purchase_date TEXT→DATE('' 会炸 cast, 转 NULL)。created_at 保持 TEXT, 原样透传。
def _dec(v):
    from decimal import Decimal
    return None if v is None else Decimal(str(v))


def _date_or_none(v):
    from datetime import date
    if v in (None, ""):
        return None
    return v if isinstance(v, date) else date.fromisoformat(str(v)[:10])


def _dir_int(v):
    return None if v is None else {"LONG": 1, "SHORT": 0}.get(str(v).upper())


_HOLDINGS_MAP = {
    "rename": {"stock_code": "code", "stock_name": "name", "broker": "broker_id"},
    "convert": {
        "shares": _dec, "cost_price": _dec, "last_price": _dec,
        "contract_multiplier": _dec, "direction": _dir_int, "purchase_date": _date_or_none,
    },
}


async def _broker_id_index(con: asyncpg.Connection):
    """PG brokers → (user_id, name) 与 (name) 两级查找表, 供 broker 名回填 id。"""
    rows = await con.fetch("SELECT id, user_id, name FROM ledger.brokers")
    by_un, by_n = {}, {}
    for r in rows:
        by_un.setdefault((r["user_id"], r["name"]), r["id"])
        by_n.setdefault(r["name"], []).append(r["id"])
    return by_un, by_n


def sqlite_cols(con: sqlite3.Connection, table: str) -> list[str]:
    return [r[1] for r in con.execute(f"PRAGMA table_info({table})").fetchall()]


async def pg_cols(con: asyncpg.Connection, table: str) -> list[str]:
    rows = await con.fetch(
        "SELECT column_name FROM information_schema.columns "
        "WHERE table_schema = 'ledger' AND table_name = $1 ORDER BY ordinal_position", table)
    return [r["column_name"] for r in rows]


async def reset_sequences(con: asyncpg.Connection, table: str):
    await con.execute(
        f"SELECT setval(pg_get_serial_sequence('ledger.{table}', 'id'), "
        f"GREATEST((SELECT COALESCE(MAX(id), 1) FROM ledger.{table}), 1))")


async def migrate(truncate: bool, check_only: bool) -> int:
    sq = sqlite3.connect(config.db_path)
    sq.row_factory = sqlite3.Row
    pg = await asyncpg.connect(config.pg_dsn)
    ok = True
    try:
        # 确保表存在(应用还没启动过就先建 schema + 全部表)
        await pg.execute("CREATE SCHEMA IF NOT EXISTS ledger")
        from database import init_db
        await init_db()

        for t in TABLES:
            hmap = _HOLDINGS_MAP if t == "holdings" else None
            scols = sqlite_cols(sq, t)
            if not scols:
                print(f"  [skip] {t}: SQLite 里没有这张表")
                continue
            pcols = await pg_cols(pg, t)
            # 列映射(holdings 老列名→新列名), 对不上 PG 的列丢弃并告警
            colpairs = [(c, (hmap["rename"].get(c, c) if hmap else c)) for c in scols]
            common = [pgc for (_s, pgc) in colpairs if pgc in pcols]
            missing = [s for (s, pgc) in colpairs if pgc not in pcols]
            if missing:
                print(f"  [warn] {t}: SQLite 有而 PG 没有的列 {missing}, 这些列的数据丢弃")

            src = list(sq.execute(f"SELECT {','.join(scols)} FROM {t}"))
            dst_n = await pg.fetchval(f"SELECT COUNT(*) FROM ledger.{t}")
            if check_only:
                status = "PASS" if len(src) == dst_n else "DIFF"
                if status == "DIFF":
                    ok = False
                print(f"  [{status}] {t}: sqlite={len(src)} pg={dst_n}")
                continue
            if truncate and dst_n:
                await pg.execute(f"TRUNCATE ledger.{t}")
                dst_n = 0
            if not src:
                print(f"  [ok] {t}: sqlite=0 pg={dst_n}")
                continue
            if dst_n == len(src):
                print(f"  [skip] {t}: 行数一致({dst_n}), 视为已迁移")
                continue

            bidx = await _broker_id_index(pg) if t == "holdings" else None
            has_id = "id" in common
            col_list = ",".join(common)
            ph = ",".join(f"${i+1}" for i in range(len(common)))
            # OVERRIDING SYSTEM VALUE 的位置在列清单之后、VALUES 之前:
            # 显式带 id 写入 GENERATED BY DEFAULT AS IDENTITY 列需要它
            sql = (f"INSERT INTO ledger.{t} ({col_list}) "
                   + ("OVERRIDING SYSTEM VALUE " if has_id else "")
                   + f"VALUES ({ph}) ON CONFLICT DO NOTHING")
            rows = []
            n_broker_unmatched = 0
            for r in src:
                vals = []
                for (s, pgc) in colpairs:
                    if pgc not in pcols:
                        continue
                    v = r[s]
                    conv = hmap["convert"].get(s) if hmap else None
                    if conv is not None:
                        v = conv(v)
                    if bidx is not None and pgc == "broker_id":
                        # 券商名 → id: 先按 (user_id, name) 精确, 再退同名单一匹配, 都没有→NULL
                        name = r["broker"]
                        v = None
                        if name:
                            uid = r["user_id"] if "user_id" in scols else 0
                            v = bidx[0].get((uid, name)) or (bidx[1][name][0] if len(bidx[1].get(name, [])) == 1 else None)
                            n_broker_unmatched += 0 if v else 1
                    vals.append(v)
                rows.append(tuple(vals))
            if n_broker_unmatched:
                print(f"  [warn] holdings: {n_broker_unmatched} 行的券商名在 PG brokers 里对不上, broker_id 置空")
            # asyncpg 的 executemany 单事务原子; 分批 1000 防一次太大
            n_before = await pg.fetchval(f"SELECT COUNT(*) FROM ledger.{t}")
            for i in range(0, len(rows), 1000):
                await pg.executemany(sql, rows[i:i + 1000])
            if has_id:
                await reset_sequences(pg, t)
            n_after = await pg.fetchval(f"SELECT COUNT(*) FROM ledger.{t}")
            status = "PASS" if n_after >= len(src) or (n_after - n_before) == len(rows) else "FAIL"
            if status == "FAIL":
                ok = False
            print(f"  [{status}] {t}: sqlite={len(src)} pg={n_before}→{n_after} (写入 {n_after - n_before})")
    finally:
        sq.close()
        await pg.close()
    return 0 if ok else 1


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--truncate", action="store_true", help="迁移前清空 ledger 各表(可重复跑)")
    ap.add_argument("--check", action="store_true", help="只比对行数, 不写库")
    args = ap.parse_args()
    return asyncio.run(migrate(args.truncate, args.check))


if __name__ == "__main__":
    sys.exit(main())

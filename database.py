async def get_db():
    """借一个连接(池内)。用法与旧 SQLite 版一致: execute→cursor→fetchone/fetchall,
    写完 commit(), finally close()(未提交即回滚)。"""
    return await get_conn()


async def init_db():
    """建表 + 日期列型对齐 + 代码形态迁移(全部幂等)。

    PG 版 SCHEMA 直接建最终形态——所有列、主键、唯一约束、索引都在 CREATE TABLE / CREATE INDEX
    里。旧 SQLite 库的迁移由 scripts/migrate_sqlite_to_pg.py 一次性处理, 这里只负责把 schema 落到
    库里, 并把测试库的日期列型(TEXT→DATE/TIMESTAMP)与港美股代码形态(HK.00700→00700.HK)对齐。
    """
    db = await get_db()
    try:
        await db.executescript(SCHEMA)
        await db.commit()
        await _align_date_column_types(db)
        await _ensure_schema_columns(db)
        await _migrate_code_format(db)
        await _migrate_quote_sources(db)
        await _migrate_fees_to_symbol_dict(db)
        await _migrate_code_suffix(db)
        await _migrate_exchange_to_suffix(db)
    finally:
        await db.close()



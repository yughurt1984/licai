async def add_watchlist(code: str, name: str, price: float | None):
    import datetime
    db = await get_db()
    try:
        await db.execute(
            "INSERT INTO watchlist (user_id, stock_code, stock_name, added_at, added_price) VALUES (?, ?, ?, ?, ?) "
            "ON CONFLICT (user_id, stock_code) DO UPDATE SET stock_name = excluded.stock_name, "
            "added_at = excluded.added_at, added_price = excluded.added_price, created_at = utc_now_ts()",
            (_uid(), code, name, datetime.date.today().isoformat(), price))
        # 默认落进「自选」组。它是真实分组, 所以这一步会真写一行 —— 不写的话新加的票
        # 一个组都不在, 只能在「全部」里看到。
        cur = await db.execute(
            "SELECT COALESCE(MAX(group_order),0)+1 FROM watchlist_group WHERE user_id=? AND grp=?",
            (_uid(), DEFAULT_WATCH_GROUP))
        nxt = (await cur.fetchone())[0] or 0
        await db.execute(
            "INSERT INTO watchlist_group (user_id, stock_code, grp, group_order) VALUES (?,?,?,?) "
            "ON CONFLICT (user_id, stock_code, grp) DO NOTHING",
            (_uid(), code, DEFAULT_WATCH_GROUP, nxt))
        await db.commit()
    finally:
        await db.close()


async def remove_watchlist(code: str):
    db = await get_db()

def direction_to_db(d):
    """'LONG'/'SHORT'/None → 1/0/None。未知值按 None(多头股票行的约定), 不猜。"""
    if d is None:
        return None
    return {"LONG": 1, "SHORT": 0}.get(str(d).upper())


def direction_to_app(v):
    """1/0/None → 'LONG'/'SHORT'/None。"""
    if v is None:
        return None
    return "LONG" if v == 1 else "SHORT" if v == 0 else None


def _num(v):
    """numeric(18,6) 入参: Decimal 化(float 直接给 asyncpg 编 numeric 不稳)。"""
    if v is None:
        return None
    from decimal import Decimal
    return Decimal(str(float(v)))


def _ticker_of(code: str) -> str | None:
    """纯标的代码: HK.00700→00700, 600519.SH→600519, CU2601.SHF→CU2601。"""
    c = str(code or "")
    if not c:
        return None
    return c.split(".", 1)[1] if c.upper().startswith(("HK.", "US.")) else c.split(".", 1)[0]



async def get_db():
    """借一个连接(池内)。用法与旧 SQLite 版一致: execute→cursor→fetchone/fetchall,
    写完 commit(), finally close()(未提交即回滚)。"""
    return await get_conn()


async def init_db():
    """建表 + 种子数据(全部幂等, 每次启动都跑)。

    SQLite 时代这里还有一大段 PRAGMA table_info + ALTER TABLE 补列迁移 —— PG 版 schema
    直接建最终形态(所有后补列都在 CREATE TABLE 里), 不再需要原地补列。老 SQLite 库的数据
    由 scripts/migrate_sqlite_to_pg.py 一次性导入。
    """
    db = await get_db()
    try:
        await db.executescript(SCHEMA)
        # ---- 多用户迁移(幂等): 老库补 user_id 列 + 重建旧主键/唯一约束 ----
        # 新库由 SCHEMA 直接建成新形态, 这里的 ADD COLUMN IF NOT EXISTS / 条件重建都是空操作。
        for t in ("holdings", "position_actions", "external_assets", "external_asset_actions",
                  "unwind_tranches", "custom_alerts", "alert_config",
                  "ask_session", "ask_message", "ask_run", "prompt_rule", "user_memory",
                  "trade_plan", "brokers",
                  # 下面三张的 UNIQUE 约束要重建成含 user_id, 列也必须先补上
                  "morning_briefings", "thesis_revision"):
            await db.execute(f"ALTER TABLE {t} ADD COLUMN IF NOT EXISTS user_id BIGINT NOT NULL DEFAULT 0")
        # 基金细分类型: etf(场内, 股票式市价记账) | open(场外开放式, NAV T+1)。
        # 老库按代码段位回填(深 1xxxxx / 沪 5xxxxx), 与报价层 _is_onchain_etf 同规则。
        await db.execute("ALTER TABLE external_assets ADD COLUMN IF NOT EXISTS fund_kind TEXT DEFAULT ''")
        await db.execute("UPDATE external_assets SET fund_kind='etf' "
                         "WHERE asset_type='FUND' AND COALESCE(fund_kind,'')='' AND code ~ '^[15][0-9]{5}$'")
        # 定投计划已下线: 表里只有计划定义(不含账本数据), 直接清掉
        await db.execute("DROP TABLE IF EXISTS dca_schedules")
        # 券商档案: 类型 + 期权费率/期权最低佣金/平台使用费(老库补列, 新库 SCHEMA 已带)
        await db.execute("ALTER TABLE brokers ADD COLUMN IF NOT EXISTS type TEXT NOT NULL DEFAULT 'A股'")
        await db.execute("ALTER TABLE brokers ADD COLUMN IF NOT EXISTS opt_rate DOUBLE PRECISION NOT NULL DEFAULT 0")
        await db.execute("ALTER TABLE brokers ADD COLUMN IF NOT EXISTS opt_min DOUBLE PRECISION NOT NULL DEFAULT 0")
        await db.execute("ALTER TABLE brokers ADD COLUMN IF NOT EXISTS platform_fee DOUBLE PRECISION NOT NULL DEFAULT 0")
        await db.execute("ALTER TABLE brokers ADD COLUMN IF NOT EXISTS platform_min DOUBLE PRECISION NOT NULL DEFAULT 0")
        await db.execute("ALTER TABLE brokers ADD COLUMN IF NOT EXISTS stock_unit TEXT NOT NULL DEFAULT '笔'")
        await db.execute("ALTER TABLE brokers ADD COLUMN IF NOT EXISTS etf_unit TEXT NOT NULL DEFAULT '笔'")
        await db.execute("ALTER TABLE brokers ADD COLUMN IF NOT EXISTS opt_unit TEXT NOT NULL DEFAULT '张'")
        # 基金费率可空(空=同股票费率); 老库该列带 NOT NULL, 幂等去掉
        await db.execute("ALTER TABLE brokers ALTER COLUMN etf_rate DROP NOT NULL")
        await db.execute("ALTER TABLE brokers ALTER COLUMN etf_min SET DEFAULT 0")
        # A股持仓代码统一为数据源 API 标准格式(600406.SH): 存量裸 6 位码一次性补市场后缀。
        # 港美股是 HK.x/US.x 前缀格式, 正则 ^[0-9]{6}$ 不会误伤。
        # CASE 里的列名按表参数化: position_thesis 列叫 code, 其余是 stock_code / symbol。
        def _a_suffix(col: str) -> str:
            return (f"CASE WHEN substring({col},1,3)='920' OR substring({col},1,1) IN ('4','8') THEN '.BJ' "
                    f"WHEN substring({col},1,1) IN ('5','6','9') THEN '.SH' ELSE '.SZ' END")
        for t in ("position_thesis", "trade_plan"):                       # 这两张列名是 code
            await db.execute(f"UPDATE {t} SET code = code || {_a_suffix('code')} WHERE code ~ '^[0-9]{{6}}$'")
        for t in ("holdings", "position_actions", "unwind_plans", "watchlist"):
            await db.execute(f"UPDATE {t} SET stock_code = stock_code || {_a_suffix('stock_code')} WHERE stock_code ~ '^[0-9]{{6}}$'")
        # 行情库快照同步换新代码(老裸码行不作废, 直接改名, 免得刷新前无价可读)
        await db.execute(f"UPDATE market.quote_latest SET symbol = symbol || {_a_suffix('symbol')} WHERE symbol ~ '^[0-9]{{6}}$'")
        # 期货/期权: 每手乘数(老库补列, 新库 SCHEMA 已带)
        await db.execute("ALTER TABLE external_assets ADD COLUMN IF NOT EXISTS contract_multiplier DOUBLE PRECISION DEFAULT 1")
        # 底稿表 is_etf → asset_type(全资产类型: a_stock/etf/hk_stock/us_stock/fut/opt/fund/crypto)。
        # 回填后删老列: 留着就是第二本账, 谁读到的都是搬迁那一刻的快照。
        await db.execute("ALTER TABLE symbol_dict ADD COLUMN IF NOT EXISTS asset_type TEXT")
        # symbol_dict 新结构(数据源 API 标准格式): code=代码+市场(600111.SH), ticker=裸码, 交易所/币种
        await db.execute("ALTER TABLE symbol_dict ADD COLUMN IF NOT EXISTS ticker TEXT DEFAULT ''")
        await db.execute("ALTER TABLE symbol_dict ADD COLUMN IF NOT EXISTS exchange TEXT DEFAULT ''")
        await db.execute("ALTER TABLE symbol_dict ADD COLUMN IF NOT EXISTS currency TEXT DEFAULT ''")
        cur = await db.execute("SELECT COUNT(*) FROM information_schema.columns "
                               "WHERE table_schema='ledger' AND table_name='symbol_dict' AND column_name='is_etf'")
        if (await cur.fetchone())[0]:
            await db.execute("UPDATE symbol_dict SET asset_type = CASE WHEN COALESCE(is_etf,0)=1 THEN 'etf' ELSE 'a_stock' END "
                             "WHERE asset_type IS NULL")
            await db.execute("ALTER TABLE symbol_dict DROP COLUMN is_etf")
        await db.execute("UPDATE symbol_dict SET asset_type = 'a_stock' WHERE asset_type IS NULL")
        _PK_NEW = {
            "app_config": ("user_id", "key"),
            "watchlist": ("user_id", "stock_code"),
            "watchlist_group": ("user_id", "stock_code", "grp"),
            "unwind_plans": ("user_id", "stock_code"),
            "position_thesis": ("user_id", "code"),
            "cashflow_monthly": ("user_id", "month"),
            "portfolio_snapshots": ("user_id", "snap_date"),
        }
        for t, cols in _PK_NEW.items():
            await db.execute(f"ALTER TABLE {t} ADD COLUMN IF NOT EXISTS user_id BIGINT NOT NULL DEFAULT 0")
            cur = await db.execute(
                "SELECT tc.constraint_name, kcu.column_name FROM information_schema.table_constraints tc "
                "JOIN information_schema.key_column_usage kcu ON tc.constraint_name = kcu.constraint_name "
                "AND tc.table_schema = kcu.table_schema "
                "WHERE tc.table_schema = 'ledger' AND tc.table_name = ? AND tc.constraint_type = 'PRIMARY KEY'", (t,))
            by_c: dict = {}
            for r in await cur.fetchall():
                by_c.setdefault(r[0], []).append(r[1])
            have = next((sorted(v) for v in by_c.values()), None)
            if have is not None and have != sorted(cols):
                for cname in by_c:
                    await db.execute(f"ALTER TABLE {t} DROP CONSTRAINT {cname}")
                await db.execute(f"ALTER TABLE {t} ADD PRIMARY KEY ({','.join(cols)})")
        _UNIQ_NEW = {
            "morning_briefings": (("stock_code", "briefing_date"), ("user_id", "stock_code", "briefing_date")),
            "thesis_revision": (("code", "rev"), ("user_id", "code", "rev")),
            "alert_config": (("stock_code",), ("user_id", "stock_code")),
            "brokers": (("user_id", "name"), ("user_id", "name", "type")),
            "holdings": (("stock_code",), ("user_id", "stock_code")),
        }
        for t, (old_cols, new_cols) in _UNIQ_NEW.items():
            cur = await db.execute(
                "SELECT tc.constraint_name, kcu.column_name FROM information_schema.table_constraints tc "
                "JOIN information_schema.key_column_usage kcu ON tc.constraint_name = kcu.constraint_name "
                "AND tc.table_schema = kcu.table_schema "
                "WHERE tc.table_schema = 'ledger' AND tc.table_name = ? AND tc.constraint_type = 'UNIQUE'", (t,))
            by_c = {}
            for r in await cur.fetchall():
                by_c.setdefault(r[0], []).append(r[1])
            if not any(sorted(v) == sorted(new_cols) for v in by_c.values()):
                for cname, cols_ in by_c.items():
                    if sorted(cols_) == sorted(old_cols):
                        await db.execute(f"ALTER TABLE {t} DROP CONSTRAINT {cname}")
                await db.execute(f"ALTER TABLE {t} ADD UNIQUE ({','.join(new_cols)})")
        # user_id 索引(列已确保存在)
        for t in ("holdings", "position_actions", "external_assets", "external_asset_actions",
                  "watchlist", "position_thesis", "ask_session", "trade_plan",
                  "brokers", "user_memory"):
            await db.execute(f"CREATE INDEX IF NOT EXISTS idx_{t}_user ON {t}(user_id)")
        await db.commit()

        # 券商种子: 只放一条 user_id=0 的「默认券商」模板(幂等)。每个用户自己的券商档案在
        # 注册时从这份模板复制(init_user_brokers), 之后各自独立维护; 模板本身可直接在数据库手工改。
        await db.execute(
            "INSERT INTO brokers (user_id, name, type, stock_rate, stock_unit, stock_min, etf_rate, etf_unit, etf_min, "
            "opt_rate, opt_unit, opt_min, platform_fee, platform_min, is_default) "
            "VALUES (0, '默认券商', 'A股', 0.00025, '笔', 5.0, NULL, '笔', 0.0, 0.0, '张', 0.0, 0.0, 0.0, 1) "
            "ON CONFLICT (user_id, name, type) DO NOTHING")
        # 一次性闸门: 把「还没归组」的票补进默认组「自选」。「自选」是一个真实分组, 不是
        # "没有分组" —— 一只票可以同时在「自选」和「金矿」里。只能跑一次: 跑第二遍会把用户
        # 后来从「自选」里取消勾选的票又塞回去(他明确只想留「金矿」)。拿 app_config 一个键
        # 当一次性闸门。迁移库自带这个键(app_config 里有), 天然跳过。
        cursor = await db.execute(
            "SELECT value FROM app_config WHERE key = 'watchlist_default_group_filled'")
        if not await cursor.fetchone():
            await db.execute(
                "INSERT INTO watchlist_group (stock_code, grp, group_order) "
                "SELECT w.stock_code, ?, COALESCE(w.sort_order, 0) FROM watchlist w "
                "WHERE NOT EXISTS (SELECT 1 FROM watchlist_group g WHERE g.stock_code = w.stock_code) "
                "ON CONFLICT DO NOTHING",
                (DEFAULT_WATCH_GROUP,))
            await db.execute(
                "INSERT INTO app_config (user_id, key, value) VALUES (0, 'watchlist_default_group_filled', '1') "
                "ON CONFLICT (user_id, key) DO NOTHING")
        await db.commit()

        # Seed external_asset_actions: 给已有 external_assets 还没 actions 的, 按当前 cost_amount 补一条 BUY/DEPOSIT
        cursor = await db.execute("""
            SELECT a.user_id, a.id, a.asset_type, a.cost_amount, a.shares, a.start_date, a.created_at
            FROM external_assets a
            WHERE NOT EXISTS (
                SELECT 1 FROM external_asset_actions ea WHERE ea.asset_id = a.id AND ea.user_id = a.user_id
            )
        """)
        rows = await cursor.fetchall()
        for r in rows:
            asset_id = r["id"]
            atype = r["asset_type"] or ""
            cost = float(r["cost_amount"] or 0)
            shares = r["shares"]
            unit_price = None
            if atype in ("FUND", "CRYPTO") and shares and float(shares) > 0:
                unit_price = round(cost / float(shares), 6) if cost > 0 else None
            action_type = "BUY" if atype in ("FUND", "CRYPTO", "BOT") else "DEPOSIT"
            seed_date = (r["start_date"] or str(r["created_at"] or "")[:10]) or None
            await db.execute(
                """INSERT INTO external_asset_actions
                   (user_id, asset_id, action_type, amount, shares, unit_price, trade_date, note)
                   VALUES (?, ?, ?, ?, ?, ?, ?, 'initial (auto-migrated)')""",
                (r["user_id"], asset_id, action_type, cost, float(shares) if shares else None, unit_price, seed_date),
            )
            print(f"[migration] Seeded {action_type} for asset#{asset_id} ({atype}): ¥{cost} on {seed_date}")
        await db.commit()

        # Seed thesis_revision: 已有的买入逻辑补一条 rev=1。
        # facts 留空是刻意的 —— 那时候没存快照, 编一个"用今天的数字当第一版事实"会让漂移分析
        # 把这段时间的变化全算成 0。空快照在下游被显式当作"当时没记"。
        cursor = await db.execute(
            "SELECT user_id, code, thesis, created_at FROM position_thesis t "
            "WHERE NOT EXISTS (SELECT 1 FROM thesis_revision r WHERE r.code = t.code AND r.user_id = t.user_id)")
        rows = await cursor.fetchall()
        for r in rows:
            await db.execute(
                "INSERT INTO thesis_revision (user_id, code, rev, thesis, facts, created_at) VALUES (?, ?, 1, ?, '', ?)",
                (r["user_id"], r["code"], r["thesis"], r["created_at"]),
            )
            print(f"[migration] Seeded thesis rev1 for {r['code']} (无事实快照)")
        await db.commit()
    finally:
        await db.close()



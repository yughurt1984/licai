def _norm_holding_row(r: dict) -> dict:
    """holdings 库行 → 应用层字典: 列改名映射(code→stock_code 等) + 类型归一
    (Decimal→float, direction 1/0→'LONG'/'SHORT', broker_id→券商名由调用方补)。
    下游(账本/路由/前端)按老形态的键与类型消费, 不感知字段调整。"""
    from decimal import Decimal
    from datetime import date as _d
    r["stock_code"] = r.pop("code", None)
    r["stock_name"] = r.pop("name", None)
    for k in ("shares", "cost_price", "last_price", "contract_multiplier"):
        if isinstance(r.get(k), Decimal):
            r[k] = float(r[k])
    v = r.get("purchase_date")
    if isinstance(v, _d):
        r["purchase_date"] = v.isoformat()
    r["direction"] = direction_to_app(r.get("direction"))
    return r


# holdings 行 LEFT JOIN assets_classify: 把分类目录的大类/中类/小类名透传给前端,

_OLD_CODE_RE = "^HK\\.[0-9]+$|^US\\.[0-9A-Za-z.]+"    # 旧前缀形态(HK.00700 / US.SNDK / US.BRK.B)


def _flip_code(old: str) -> str:
    """HK.00700 → 00700.HK(HK 主体补前导零); US.SNDK / US.BRK.B → SNDK.US / BRK.B.US。"""
    if old.startswith("HK."):
        return old[3:].zfill(5) + ".HK"
    if old.startswith("US."):
        return old[3:] + ".US"
    return old


async def _migrate_code_format(db) -> None:
    """把旧前缀形态的港美股代码翻成标准形态(幂等: 只动仍匹配旧形态的行)。"""
    # ① symbol_dict: 标准行已存在时直接删旧形态重复行(它们是行情登记泄漏的),
    #    没有标准孪生的改写过去; 顺便补 suffix(市场段位)与美股裸码行(→ ticker.US)。
    try:
        await db.execute(
            "DELETE FROM ledger.symbol_dict a WHERE a.code ~ ? AND EXISTS ("
            "  SELECT 1 FROM ledger.symbol_dict b WHERE b.code = CASE"
            "    WHEN a.code ~ '^HK\\.' THEN lpad(split_part(a.code, '.', 2), 5, '0') || '.HK'"
            "    ELSE regexp_replace(a.code, '^US\\.', '') || '.US' END)", (_OLD_CODE_RE,))
        cur = await db.execute(
            "SELECT code FROM ledger.symbol_dict WHERE code ~ ?", (_OLD_CODE_RE,))
        olds = [r[0] for r in await cur.fetchall()]
        for old in olds:
            await db.execute("UPDATE ledger.symbol_dict SET code = ?, suffix = ? WHERE code = ?",
                             (_flip_code(old), "HK" if _flip_code(old).endswith(".HK") else "US", old))
        await db.execute(
            "UPDATE ledger.symbol_dict SET suffix = CASE WHEN code ~ '\\.HK$' THEN 'HK'"
            " WHEN code ~ '\\.US$' THEN 'US' END "
            "WHERE (suffix IS NULL OR suffix = '') AND code ~ '\\.(HK|US)$'")
        await db.execute(
            "UPDATE ledger.symbol_dict SET code = code || '.US', suffix = 'US' "
            "WHERE code NOT LIKE '%.%' AND sub_assets_type LIKE 'us%' "
            "AND NOT EXISTS (SELECT 1 FROM ledger.symbol_dict b WHERE b.code = ledger.symbol_dict.code || '.US')")
        await db.commit()
        if olds:
            print(f"[db] ledger.symbol_dict: {len(olds)} 行旧形态码已翻标准")
    except Exception as e:
        print(f"[db] ! symbol_dict 代码形态迁移失败(跳过): {str(e)[:160]}")

    # ② 其余表逐行翻转(唯一/主键冲突 → quote_latest 删旧形态泄漏行, 其余保留标准行跳过)
    for table, col, _pk in _CODE_FLIP_TABLES:
        try:
            cur = await db.execute(f'SELECT "{col}" FROM {table} WHERE "{col}" ~ ?', (_OLD_CODE_RE,))
            olds = [r[0] for r in await cur.fetchall()]
            flipped = 0
            for old in olds:
                new = _flip_code(old)
                try:
                    await db.execute(f'UPDATE {table} SET "{col}" = ? WHERE "{col}" = ?', (new, old))
                    flipped += 1
                except Exception as e:
                    if table.endswith("quote_latest"):
                        # 行情登记泄漏的旧形态行: 标准行已存在, 删旧行去重
                        await db.execute(f'DELETE FROM {table} WHERE "{col}" = ?', (old,))
                        print(f"[db] {table}.{old} 与标准行重复 → 删旧形态行")
                    else:
                        print(f"[db] ! {table}.{old} → {new} 冲突跳过: {str(e)[:100]}")
            if olds:
                await db.commit()
                print(f"[db] {table}: {flipped}/{len(olds)} 行代码翻成标准形态")
        except Exception as e:
            print(f"[db] ! {table} 代码形态迁移失败(跳过): {str(e)[:160]}")



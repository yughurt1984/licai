async def set_thesis(code: str, thesis: str, name: str = "", facts: str = "") -> dict:
    """写入/更新买入逻辑, 并在**正文真的变了**的时候追加一条修订。

    只在正文变化时追加: 前端每次打开弹窗点保存都会 PUT 一次, 原文没动也记一版会把修订史灌成
    一堆同文, 漂移分析里"改过几次"就废了。facts 是调用方在保存那一刻取的事实快照(JSON 串),
    取不到就传空 —— 空要当"当时没记"处理, 不能当"事实没变"。
    """
    db = await get_db()
    try:
        cur = await db.execute("SELECT thesis FROM position_thesis WHERE user_id = ? AND code = ?", (_uid(), code))
        row = await cur.fetchone()
        changed = (row is None) or ((row["thesis"] or "").strip() != (thesis or "").strip())
        await db.execute(
            "INSERT INTO position_thesis (user_id, code, name, thesis, updated_at) VALUES (?, ?, ?, ?, utc_now_ts()) "
            "ON CONFLICT (user_id, code) DO UPDATE SET thesis = excluded.thesis, "
            "name = CASE WHEN excluded.name != '' THEN excluded.name ELSE position_thesis.name END, "
            "updated_at = utc_now_ts()",
            (_uid(), code, name, thesis),
        )
        rev = 0
        if changed:
            cur = await db.execute("SELECT COALESCE(MAX(rev), 0) FROM thesis_revision WHERE user_id = ? AND code = ?", (_uid(), code))
            rev = int((await cur.fetchone())[0]) + 1
            await db.execute(
                "INSERT INTO thesis_revision (user_id, code, rev, thesis, facts) VALUES (?, ?, ?, ?, ?)",
                (_uid(), code, rev, thesis, facts or ""),
            )
        await db.commit()
        return {"appended": changed, "rev": rev}
    finally:
        await db.close()



# purchase_date 纯日期 → DATE。测试库(或任何 TEXT 老库)启动时逐列对齐, 幂等。
_DATE_COL_TYPES = {"purchase_date": "DATE"}
_DATE_COL_NAMES = ("purchase_date", "created_at", "updated_at", "quote_time", "fetched_at")


async def _align_date_column_types(db) -> None:
    """把 5 个日期字段名下仍是 text/varchar 的列 ALTER 成真类型。

    幂等: 先查 information_schema, 已是目标类型的不动。USING NULLIF(col,'')::type
    只防空串 cast 报错, 不做任何数据修复 —— 老库里有脏值会在这里显式报错跳过, 不挡启动。
    """
    cur = await db.execute(
        "SELECT table_schema, table_name, column_name FROM information_schema.columns "
        "WHERE table_schema IN ('ledger', 'market') "
        "AND data_type IN ('text', 'character varying', 'character') "
        "AND column_name = ANY(?)",
        (list(_DATE_COL_NAMES),))
    todo = await cur.fetchall()
    for schema, table, col in todo:
        typ = _DATE_COL_TYPES.get(col, "TIMESTAMP")
        try:
            # 老列可能挂着 text 默认值(utc_now_text()), 默认表达式与目标类型不符会让 ALTER TYPE
            # 直接报"默认值不能转换" —— 先摘掉, 改型后按新 SCHEMA 语义补回(仅 created_at/updated_at)
            await db.execute(f'ALTER TABLE {schema}."{table}" ALTER COLUMN "{col}" DROP DEFAULT')
            await db.execute(f'ALTER TABLE {schema}."{table}" ALTER COLUMN "{col}" TYPE {typ} '
                             f'USING NULLIF("{col}", \'\')::{typ}')
            if col in ("created_at", "updated_at"):
                await db.execute(f'ALTER TABLE {schema}."{table}" ALTER COLUMN "{col}" SET DEFAULT utc_now_ts()')
            print(f"[db] {schema}.{table}.{col}: text → {typ}")
        except Exception as e:
            print(f"[db] ! {schema}.{table}.{col} 改型失败(跳过, 不挡启动): {str(e)[:160]}")


# 代码形态迁移: 港美股旧前缀形态(HK.00700 / US.SNDK) → 标准形态(00700.HK / SNDK.US)。
